def clean_text(text):
    """Clean text by removing extra whitespace and special characters."""
    return text.strip().strip('"').strip()

def parse_songs(raw_text):
    """Parse the raw song text into a list of dictionaries."""
    songs = []
    # Split into lines and remove empty lines
    lines = [line.strip() for line in raw_text.split('\n') if line.strip()]
    
    for line in lines:
        # Skip empty lines or lines that are just numbers
        if not line or line.isdigit():
            continue
            
        # Remove the number prefix if it exists
        if '. ' in line:
            line = line.split('. ', 1)[1]
            
        # Match the pattern: song name (artist name)
        match = re.match(r'^(.*?)\s*[（(](.*?)[)）]$', line)
        if match:
            song_name = clean_text(match.group(1))
            artist_name = clean_text(match.group(2))
            songs.append({
                "songName": song_name,
                "levelAuthorName": artist_name
            })
            continue
            
        # Try alternative pattern: song name - artist name
        match = re.split(r'\s+[-–]\s+', line)
        if len(match) == 2:
            song_name = clean_text(match[0])
            artist_name = clean_text(match[1])
            songs.append({
                "songName": song_name,
                "levelAuthorName": artist_name
            })

    return songs

