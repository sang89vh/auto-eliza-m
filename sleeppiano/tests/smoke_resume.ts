/**
 * The composition cases the per-step smoke tests could not reach: state left behind
 * by an interrupted run. No Suno, no YouTube, no OpenAI -- purely the selection and
 * carry-over logic that decides whether a re-run pays for the same work twice.
 */
import fs from 'node:fs';
import path from 'node:path';
import { db, migrate, selectSongsForRun, songsByStatus, getSong, saveAudio, nowIso, closeDb } from '../src/lib/db.js';
import { config } from '../src/lib/config.js';

migrate();
const database = db();
let failures = 0;
const check = (label: string, ok: boolean, detail = ''): void => {
  console.log(`  ${ok ? 'PASS' : 'FAIL'}: ${label}${detail ? ' — ' + detail : ''}`);
  if (!ok) failures++;
};

// ---------- US-07 AC1: killed mid-Step 3 ----------
console.log('\n=== US-07 AC1: songs left GENERATED by a killed run ===');
database.exec("UPDATE my_song SET piano_status='INIT', piano_audio_path=NULL, piano_duration_sec=NULL, piano_video_path=NULL");
// Two songs already downloaded (40 min of audio) when the process died.
database.prepare(
  "UPDATE my_song SET piano_status='GENERATED', piano_audio_path=?, piano_duration_sec=1200, piano_updated_at=? WHERE id IN (1223,1224)"
).run(JSON.stringify(['/tmp/a.wav']), nowIso());

const selected = selectSongsForRun(config.maxSongsPerRun);
check('Step 1 still returns only INIT/PROMPTED (US-02 AC1)',
  selected.every((s) => s.piano_status === 'INIT' || s.piano_status === 'PROMPTED'));
check('the two GENERATED songs are NOT in the Step 1 selection',
  !selected.some((s) => s.id === 1223 || s.id === 1224));

// This is the orchestrator's carry-over, verbatim.
const selectedIds = new Set(selected.map((s) => s.id));
const carriedOver = songsByStatus(['GENERATED', 'CONVERTED']).filter((s) => !selectedIds.has(s.id));
const working = [...selected, ...carriedOver];

check('carry-over picks both up', carriedOver.length === 2, `ids ${carriedOver.map((s) => s.id).join(',')}`);

// Step 3's own tally, verbatim.
const alreadyDone = working.filter((s) => s.piano_status === 'GENERATED' || s.piano_status === 'CONVERTED');
const startingSeconds = alreadyDone.reduce((sum, s) => sum + (s.piano_duration_sec ?? 0), 0);
check('Step 3 starts its minute count at 40, not 0', startingSeconds === 2400, `${startingSeconds / 60} min`);
check('so it generates 80 more minutes, not another 120',
  (config.dailyTargetMinutes * 60 - startingSeconds) / 60 === 80);
check('Step 4 sees the orphans, so their audio gets converted',
  working.filter((s) => s.piano_status === 'GENERATED').length === 2);

// ---------- The runaway-merge case ----------
console.log('\n=== CONVERTED orphans after a failed merge validation ===');
database.exec("UPDATE my_song SET piano_status='CONVERTED', piano_video_path='[\"/tmp/a.mp4\"]' WHERE id IN (1223,1224)");
const sel2 = selectSongsForRun(config.maxSongsPerRun);
const ids2 = new Set(sel2.map((s) => s.id));
const carried2 = songsByStatus(['GENERATED', 'CONVERTED']).filter((s) => !ids2.has(s.id));
const budget2 = carried2.reduce((sum, s) => sum + (s.piano_duration_sec ?? 0), 0);
check('CONVERTED orphans also count toward the target (no 240-min runaway merge)',
  budget2 === 2400, `${budget2 / 60} min carried`);
check('and they are in the merge input exactly once',
  carried2.filter((s) => s.id === 1223).length === 1);

// ---------- PRD §10 / US-06 AC5: Step 6 resume ----------
console.log('\n=== PRD §10: resume at STEP6 after an upload failure ===');
const { previousRun } = await import('../src/lib/db.js');
database.exec('DELETE FROM pipeline_run');
database.prepare("INSERT INTO pipeline_run (id,run_date,status,current_step,created_at) VALUES (7,'2026-08-30','FAILED','STEP6',?)").run(nowIso());
database.prepare("INSERT INTO pipeline_run (id,run_date,status,current_step,created_at) VALUES (8,'2026-08-30','RUNNING','STEP0',?)").run(nowIso());

const prev = previousRun(8);
check('previousRun() sees the FAILED run, not the RUNNING one',
  prev?.id === 7 && prev?.status === 'FAILED', `got id=${prev?.id} status=${prev?.status}`);

const { latestRun } = await import('../src/lib/db.js');
check('(latestRun() would have masked it — that was the bug)', latestRun()?.id === 8);

// The rest of the resume precondition: today's merged file + tracklist.json on disk.
const stamp = new Date();
const pad = (n: number): string => String(n).padStart(2, '0');
const dateStamp = `${stamp.getFullYear()}${pad(stamp.getMonth() + 1)}${pad(stamp.getDate())}`;
const runRoot = path.join(config.outputDir, `run_${dateStamp}_0900`);
fs.mkdirSync(path.join(runRoot, 'final'), { recursive: true });
fs.mkdirSync(path.join(runRoot, 'logs'), { recursive: true });
fs.writeFileSync(path.join(runRoot, 'final', `final_${dateStamp}.mp4`), 'not-a-real-mp4-but-non-empty');
fs.writeFileSync(path.join(runRoot, 'final', 'tracklist.json'), JSON.stringify(
  [{ songId: 1223, title: 'Autumn Garden Piano', startSec: 0, durationSec: 200, videoPath: '' }]));

const { findExistingFinalVideo } = await import('../src/lib/runFolder.js');
const found = findExistingFinalVideo(dateStamp);
check('findExistingFinalVideo locates today\'s merged file', !!found, found?.videoPath ?? 'not found');

console.log(`\n=== ${failures === 0 ? 'ALL RESUME CHECKS PASSED' : failures + ' CHECK(S) FAILED'} ===`);
closeDb();
process.exit(failures === 0 ? 0 : 1);
